------------------------------------------------------------------------------
-- Bounds

-- | Most formula cells one workbook will be evaluated for. Past this the rest
-- stay blank and are counted as uncomputed — the same outcome as a formula we
-- do not understand, and reported the same way.
maxFormulaCells :: Int
maxFormulaCells = 50000

-- | Total cell reads across the workbook, counted whether they hit the memo or
-- not. A sheet of whole-column @SUM(A:A)@s is quadratic in the honest case and
-- worse in a hostile one, and the reads inside a range are where that cost
-- lives — which is why this counts /reads/ and not formulas. A cell that runs
-- the budget out shows @#NUM!@ rather than making the editor hang.
maxSteps :: Int
maxSteps = 8000000

-- | Deepest chain of cell-to-cell references followed.
--
-- This is a stack guard, not the cycle detector: a genuine cycle is caught
-- exactly, by set membership on the cells currently being evaluated, so
-- anything that reaches this limit is a chain that is merely very long and is
-- reported as @#NUM!@ rather than mislabelled circular. It is set well past
-- any real workbook's chain because chains /are/ real — a running-total
-- column is one link per row — and because the evaluation order resolves an
-- ascending one at depth 1 anyway.
maxDepth :: Int
maxDepth = 10000

------------------------------------------------------------------------------
-- Values

-- | A cell's value. 'VBlank' is a distinct thing from an empty string: it is
-- zero in arithmetic, empty in text, and false for @ISBLANK@.
data Value
  = VNum  !Double
  | VText !Text
  | VBool !Bool
  | VErr  !Text     -- ^ An Excel error value (@#DIV\/0!@, @#VALUE!@, …).
  | VBlank
  deriving (Eq, Show)

errValue, errNum, errDiv0, errRef, errName, errNA, errCycle :: Value
errValue = VErr "#VALUE!"
errNum   = VErr "#NUM!"
errDiv0  = VErr "#DIV/0!"
errRef   = VErr "#REF!"
errName  = VErr "#NAME?"
errNA    = VErr "#N/A"
-- Not one of Excel's: Excel resolves a circular reference to 0 and warns in
-- its status bar, which a terminal reader has no way to do. Saying so in the
-- cell is the honest equivalent.
errCycle = VErr "#CYCLE!"

-- | Render a number the way the file's own cached values are written: plainly,
-- with no thousands separators and no number format applied, because none is
-- applied to the values we read either.
showNumber :: Double -> Text
showNumber d
  | isNaN d || isInfinite d = "#NUM!"
  | d == 0 = "0"
  | isInt && ad < 1e15 = T.pack (show (round d :: Integer))
  | ad >= 1e15 || ad < 1e-10 = T.pack (showEFloat (Just 6) d "")
  | otherwise = trimZeros (T.pack (showFFloat (Just 10) d ""))
  where
    ad = abs d
    isInt = d == fromIntegral (round d :: Integer)
    trimZeros t
      | T.any (== '.') t = let t' = T.dropWhileEnd (== '0') t
                           in if "." `T.isSuffixOf` t' then T.init t' else t'
      | otherwise = t

-- | A value as text, for display and for the @&@ operator.
asText :: Value -> Text
asText v = case v of
  VNum n  -> showNumber n
  VText t -> t
  VBool b -> if b then "TRUE" else "FALSE"
  VErr e  -> e
  VBlank  -> T.empty

-- | A value in a numeric context. Text is parsed (Excel coerces @"3"@), a
-- blank is zero, an error propagates.
asNum :: Value -> Either Value Double
asNum v = case v of
  VNum n  -> Right n
  VBool b -> Right (if b then 1 else 0)
  VBlank  -> Right 0
  VErr _  -> Left v
  VText t -> maybe (Left errValue) Right (readNumber t)

asBool :: Value -> Either Value Bool
asBool v = case v of
  VBool b -> Right b
  VNum n  -> Right (n /= 0)
  VBlank  -> Right False
  VErr _  -> Left v
  VText t -> case T.toUpper (T.strip t) of
               "TRUE"  -> Right True
               "FALSE" -> Right False
               _       -> Left errValue

-- Parse a number the way a cell's text would be read: optional sign, digits,
-- decimal point, exponent. Deliberately strict — "3 apples" is not 3.
readNumber :: Text -> Maybe Double
readNumber t0
  | T.null t = Nothing
  | otherwise = case reads (fixup (T.unpack t)) :: [(Double, String)] of
      [(d, rest)] | all isSpace rest -> Just d
      _ -> Nothing
  where
    t = T.strip t0
    -- Haskell's reader wants a digit either side of the point and no leading
    -- '+'; spreadsheets write ".5" and "+3" freely.
    fixup s = case s of
      ('+' : r)       -> fixup r
      ('.' : r)       -> '0' : '.' : r
      ('-' : '.' : r) -> '-' : '0' : '.' : r
      _               -> case break (== '.') s of
                           (a, '.' : b) | null b || not (isDigit (head b)) -> a ++ ".0"
                           _ -> s

------------------------------------------------------------------------------
-- The formula language

-- | A parsed formula. Cell references carry an optional sheet name; a
-- reference with no sheet means the one the formula is on.
data Expr
  = ENum !Double
  | EStr !Text
  | EBool !Bool
  | ELitErr !Text                       -- ^ An error typed into the formula (@#N\/A@).
  | ERef !(Maybe Text) !Int !Int        -- ^ sheet, column, row (both 0-based).
  | EArea !(Maybe Text) !Int !Int !Int !Int
    -- ^ sheet, and the inclusive corners @c0 r0 c1 r1@. An open end
    -- (@'maxBound'@) is a whole-column @A:A@ or whole-row @1:1@ reference,
    -- clamped to the sheet when it is read.
  | ENeg !Expr
  | EPercent !Expr
  | EBin !Text !Expr !Expr
  | ECall !Text ![Expr]
  deriving (Eq, Show)

-- | Parse a formula's source (with or without a leading @=@).
--
-- 'Nothing' means "this reader does not understand this", which the caller
-- turns into a cell left exactly as it was. That covers a syntax we do not
-- model (array constants, defined names, structured table references) as well
-- as a genuinely malformed file, and both deserve the same answer: silence.
parseFormula :: Text -> Maybe Expr
parseFormula src0 = case pExpr (lexer src) of
  Just (e, []) | knownCalls e -> Just e
  _                           -> Nothing
  where
    src = T.dropWhile (== '=') (T.strip src0)
    -- A function we do not have is checked up front rather than during
    -- evaluation, so "we cannot compute this" is one answer given once and
    -- never half a result.
    knownCalls e = case e of
      ECall f as -> T.toUpper f `elem` supportedFunctions && all knownCalls as
      ENeg a     -> knownCalls a
      EPercent a -> knownCalls a
      EBin _ a b -> knownCalls a && knownCalls b
      _          -> True

------------------------------------------------------------------------------
-- Lexing

data Tok
  = TNum !Double
  | TStr !Text
  | TName !Text          -- ^ A bare name: a function, a cell reference, TRUE…
  | TSheetName !Text !Text  -- ^ @Sheet1!A1@ — sheet and the name after the @!@.
  | TErrLit !Text
  | TOp !Text
  | TOpen | TClose | TComma | TColon
  deriving (Eq, Show)

lexer :: Text -> [Tok]
lexer t0 = go (T.dropWhile isSpace t0)
  where
    go t = case T.uncons t of
      Nothing -> []
      Just (c, r)
        | isSpace c -> go (T.dropWhile isSpace t)
        | c == '"'  -> let (s, r') = quoted r in TStr s : go r'
        | c == '\'' -> sheetQuoted r
        | c == '('  -> TOpen : go r
        | c == ')'  -> TClose : go r
        | c == ','  -> TComma : go r
        | c == ';'  -> TComma : go r          -- some locales' argument separator
        | c == ':'  -> TColon : go r
        | c == '#'  -> let (e, r') = T.span (\x -> isAlpha x || x `elem` ("/0!?" :: String)) t
                       in if T.null e then go r else TErrLit (T.toUpper e) : go r'
        | isDigit c -> number t
        | c == '.', maybe False isDigit (fmap fst (T.uncons r)) -> number t
        | isNameStart c -> name t
        | otherwise -> operator t

    quoted s = let (a, r) = T.break (== '"') s
               in case T.uncons r of
                    Just ('"', r') -> case T.uncons r' of
                      Just ('"', r'') -> let (b, r3) = quoted r'' in (a <> "\"" <> b, r3)
                      _               -> (a, r')
                    _ -> (a, T.empty)

    -- 'My Sheet'!A1 — the quoted form, which any sheet name with a space in it
    -- has to use.
    sheetQuoted s =
      let (nm, r) = T.break (== '\'') s
          r1 = T.drop 1 r
      in case T.uncons r1 of
           Just ('!', r2) -> let (n, r3) = T.span isNameChar r2
                             in TSheetName nm n : go r3
           _              -> go r1

    number t = let (ds, r) = T.span (\c -> isDigit c || c == '.') t
                   (ex, r') = expPart r
               in case readNumber (ds <> ex) of
                    Just d  -> TNum d : go r'
                    Nothing -> go r'
    expPart t = case T.uncons t of
      Just (e, r) | e == 'e' || e == 'E' ->
        let (sgn, r1) = case T.uncons r of
                          Just (s, rr) | s == '+' || s == '-' -> (T.singleton s, rr)
                          _ -> (T.empty, r)
            (ds, r2) = T.span isDigit r1
        in if T.null ds then (T.empty, t) else (T.cons 'e' (sgn <> ds), r2)
      _ -> (T.empty, t)

    name t = let (n, r) = T.span isNameChar t
             in case T.uncons r of
                  Just ('!', r') -> let (n2, r2) = T.span isNameChar r'
                                    in TSheetName n n2 : go r2
                  _ -> TName n : go r

    operator t = case [ o | o <- twoCharOps, o `T.isPrefixOf` t ] of
      (o : _) -> TOp o : go (T.drop 2 t)
      []      -> case T.uncons t of
        Just (c, r) | c `elem` ("+-*/^&=<>%" :: String) -> TOp (T.singleton c) : go r
                    | otherwise -> go r      -- a byte we have no meaning for
        Nothing -> []

    twoCharOps = ["<=", ">=", "<>"]
    isNameStart c = isAlpha c || c == '_' || c == '$'
    isNameChar c = isAlpha c || isDigit c || c `elem` ("_.$" :: String)

------------------------------------------------------------------------------
-- Parsing
--
-- Recursive descent over Excel's precedence: comparison binds loosest, then
-- concatenation, then +/-, then */, then ^, then unary minus and the postfix
-- percent. Ranges are handled where references are read, since ':' binds
-- tighter than everything.

type P a = [Tok] -> Maybe (a, [Tok])

pExpr :: P Expr
pExpr = pCompare

pCompare :: P Expr
pCompare = chain ["=", "<>", "<=", ">=", "<", ">"] pConcat

pConcat :: P Expr
pConcat = chain ["&"] pAdd

pAdd :: P Expr
pAdd = chain ["+", "-"] pMul

pMul :: P Expr
pMul = chain ["*", "/"] pPow

-- Exponentiation is left-associative in Excel (2^3^2 is 64, not 512).
pPow :: P Expr
pPow = chain ["^"] pUnary

chain :: [Text] -> P Expr -> P Expr
chain ops sub ts = do
  (l, ts1) <- sub ts
  go l ts1
  where
    go l (TOp o : rest) | o `elem` ops = do
      (r, rest') <- sub rest
      go (EBin o l r) rest'
    go l rest = Just (l, rest)

pUnary :: P Expr
pUnary (TOp "-" : ts) = fmap (\(e, r) -> (ENeg e, r)) (pUnary ts)
pUnary (TOp "+" : ts) = pUnary ts
pUnary ts = do
  (e, ts1) <- pPostfix ts
  Just (e, ts1)

pPostfix :: P Expr
pPostfix ts = do
  (e, ts1) <- pAtom ts
  Just (percents e ts1)
  where
    percents e (TOp "%" : r) = percents (EPercent e) r
    percents e r             = (e, r)

pAtom :: P Expr
pAtom ts = case ts of
  -- A whole-row range is written @1:1@, and a bare row number lexes as a
  -- number rather than a name — so it has to be recognised before the literal
  -- case below swallows it.
  (TNum d : TColon : rest) | Just n <- rowTok d -> refOrConst Nothing n (TColon : rest)
  (TNum d : r)    -> Just (ENum d, r)
  (TStr s : r)    -> Just (EStr s, r)
  (TErrLit e : r) -> Just (ELitErr e, r)
  (TOpen : r)     -> do (e, r1) <- pExpr r
                        case r1 of (TClose : r2) -> Just (e, r2); _ -> Nothing
  (TName n : TOpen : r) -> do (as, r1) <- pArgs r
                              Just (ECall n as, r1)
  (TName n : r)   -> refOrConst Nothing n r
  (TSheetName sh n : r) -> refOrConst (Just sh) n r
  _ -> Nothing
  where
    refOrConst sh n r = case T.toUpper n of
      "TRUE"  | sh == Nothing -> Just (EBool True, r)
      "FALSE" | sh == Nothing -> Just (EBool False, r)
      _ -> do
        a <- cellRef n
        case r of
          -- A range: the second half may name its own sheet in a malformed
          -- file; the first one's wins, as everywhere.
          (TColon : TName n2 : r2)        -> mkArea sh a n2 r2
          (TColon : TSheetName _ n2 : r2) -> mkArea sh a n2 r2
          (TColon : TNum d : r2) | Just n2 <- rowTok d -> mkArea sh a n2 r2
          -- A half-reference outside a range is not a cell: @=A@ is not valid
          -- Excel, and letting it through would silently read a blank where a
          -- short defined name (@VAT@, @Tax@) was meant.
          _ | uncurry max a == maxBound -> Nothing
            | otherwise -> Just (uncurry (ERef sh) a, r)
    -- @A:A@ and @1:1@ are open at *both* ends of the axis they name, not just
    -- the far one: taking the recorded 'maxBound' as the start would give an
    -- empty range, which reads on screen as a zero.
    mkArea sh (c0, r0) n2 rest = do
      (c1, r1) <- cellRef n2
      let openRow = r0 == maxBound || r1 == maxBound
          openCol = c0 == maxBound || c1 == maxBound
          (rr0, rr1) | openRow   = (0, maxBound)
                     | otherwise = (min r0 r1, max r0 r1)
          (cc0, cc1) | openCol   = (0, maxBound)
                     | otherwise = (min c0 c1, max c0 c1)
      Just (EArea sh cc0 rr0 cc1 rr1, rest)

-- A row number, as the text half of @1:1@ would have been had it lexed as a
-- name. Whole numbers only, and within a sheet's plausible height.
rowTok :: Double -> Maybe Text
rowTok d
  | d >= 1, d < 1e9, d == fromIntegral n = Just (T.pack (show n))
  | otherwise = Nothing
  where n = round d :: Integer

pArgs :: P [Expr]
pArgs (TClose : r) = Just ([], r)
pArgs ts = go ts
  where
    go t = do
      (e, t1) <- pExpr t
      case t1 of
        (TComma : t2) -> do (es, t3) <- go t2; Just (e : es, t3)
        (TClose : t2) -> Just ([e], t2)
        _             -> Nothing

-- | An A1-style reference to 0-based @(column, row)@, dollar signs ignored
-- (we never move a formula, so absolute and relative are the same thing here).
-- A column with no row (@A@) or a row with no column (@1@) is the open end of
-- a whole-column or whole-row range.
cellRef :: Text -> Maybe (Int, Int)
cellRef raw
  | T.null letters && T.null digits = Nothing
  | T.length letters > 3            = Nothing
  | T.null digits                   = Just (colNum letters, maxBound)
  | T.null letters                  = fmap (\r -> (maxBound, r)) (rowNum digits)
  | not (T.null rest)               = Nothing
  | otherwise                       = fmap (\r -> (colNum letters, r)) (rowNum digits)
  where
    t       = T.filter (/= '$') raw
    letters = T.takeWhile isAlpha (T.map toUpper t)
    afterL  = T.drop (T.length letters) t
    digits  = T.takeWhile isDigit afterL
    rest    = T.drop (T.length digits) afterL
    colNum  = subtract 1 . T.foldl' (\ !a c -> a * 26 + (ord c - ord 'A' + 1)) 0
    rowNum d | T.length d > 8 = Nothing
             | otherwise = let n = T.foldl' (\ !a c -> a * 10 + (ord c - ord '0')) 0 d
                           in if n < 1 then Nothing else Just (n - 1)

------------------------------------------------------------------------------
-- Evaluating a workbook

-- | A grid of already-displayed cell text, as "Cmedit.Xlsx" reads it.
type Grid = Seq (Seq Text)

-- | One sheet's input to the pass: what it already shows, plus the formulas
-- that came with no cached value.
data SheetIn = SheetIn
  { siName     :: !Text
  , siGrid     :: !Grid
  , siFormulas :: !(Map (Int, Int) Text)   -- ^ @(row, column)@ → formula source.
  }

-- Cell coordinates across the workbook.
type Key = (Int, Int, Int)   -- (sheet index, row, column)

data Env = Env
  { envGrids  :: !(Seq Grid)
  , envByName :: !(Map Text Int)          -- ^ Lower-cased sheet name → index.
  , envForms  :: !(Map Key Expr)
  }

-- Where evaluation currently is: which cell's formula is being evaluated (an
-- unqualified reference means that cell's sheet), which cells are open above
-- it, and how deep. A 'Set' rather than a list because a running-total column
-- is a chain thousands deep, and a linear membership test down it on every
-- cell read is quadratic in the length of the chain.
data Ctx = Ctx
  { ctxHere  :: !(Maybe Key)
  , ctxOpen  :: !(Set Key)
  , ctxDepth :: !Int
  }

ctx0 :: Ctx
ctx0 = Ctx Nothing Set.empty 0

data St = St
  { stCache :: !(Map Key Value)
  , stSteps :: !Int
  }

-- | Fill in every formula cell that came with no cached value.
--
-- Returns the completed grids, how many cells were computed, and how many were
-- left alone because this reader could not parse them or does not have the
-- function they call. The two counts are what the status bar reports: the
-- second is the honest half.
evalWorkbook :: [SheetIn] -> ([(Text, Grid)], Int, Int)
evalWorkbook sheets = (zipWith fill [0 ..] sheets, computed, unsupported)
  where
    grids = Seq.fromList (map siGrid sheets)
    env = Env
      { envGrids  = grids
      , envByName = M.fromList (zip (map (T.toLower . siName) sheets) [0 ..])
      , envForms  = parsed
      }
    -- Parse everything first: a formula we cannot read is not attempted, and
    -- is not a reference anything else can resolve through either.
    (parsed, unsupported) =
      let cells = [ ((si, r, c), src)
                  | (si, sh) <- zip [0 ..] sheets
                  , ((r, c), src) <- M.toList (siFormulas sh) ]
          taken = take maxFormulaCells cells
          ok    = [ (k, e) | (k, src) <- taken, Just e <- [parseFormula src] ]
      in (M.fromList ok, length cells - length ok)

    -- In key order, which is row-major per sheet. Not required for
    -- correctness (anything unresolved is evaluated on demand) but it means
    -- the common downward-accumulating chain is already cached by the time
    -- each link asks for the one above it, so it resolves at depth 1.
    results = fst (foldl' step (M.empty, St M.empty 0) (M.keys parsed))
      where step (acc, st) k =
              let (v, st') = evalCell env ctx0 k st
              in (M.insert k v acc, st')

    computed = M.size results

    fill si sh = (siName sh, foldl' put (siGrid sh) (M.toList (siFormulas sh)))
      where
        put g ((r, c), _) = case M.lookup (si, r, c) results of
          Nothing -> g
          Just v  -> setCell r c (asText v) g

-- Write one computed value into the grid.
--
-- 'Seq.adjust'' rather than 'Seq.update', at both levels: @update@ stores
-- @const x@ applied to the value it replaced, so folding it over twenty
-- thousand formula cells builds twenty thousand nested thunks over the grid
-- and nothing is released until the renderer forces them. This is the same
-- trap 'Cmedit.TextBuffer' documents for buffer lines.
setCell :: Int -> Int -> Text -> Grid -> Grid
setCell r c t g = case Seq.lookup r g of
  Nothing  -> g
  Just row | c < 0 || c >= Seq.length row -> g
           | otherwise -> Seq.adjust' (const (Seq.adjust' (const t) c row)) r g

-- | Evaluate one cell, memoised, with the set of cells currently being
-- evaluated as the cycle guard.
evalCell :: Env -> Ctx -> Key -> St -> (Value, St)
evalCell env ctx k st
  | stSteps st >= maxSteps = (errNum, st)
  | otherwise = case M.lookup k (stCache st1) of
      Just v  -> (v, st1)
      Nothing
        | Set.member k (ctxOpen ctx) -> (errCycle, st1)
        | ctxDepth ctx >= maxDepth   -> (errNum, st1)
        | otherwise -> case M.lookup k (envForms env) of
            Nothing -> (literalAt env k, st1)
            Just e  ->
              let ctx' = Ctx { ctxHere  = Just k
                             , ctxOpen  = Set.insert k (ctxOpen ctx)
                             , ctxDepth = ctxDepth ctx + 1 }
                  (v, st2) = evalExpr env ctx' e st1
              in (v, st2 { stCache = M.insert k v (stCache st2) })
  where st1 = st { stSteps = stSteps st + 1 }

-- The value a cell has without being computed: whatever text it already
-- shows, read as a number where it looks like one (the grid is text, because
-- that is what the view draws).
literalAt :: Env -> Key -> Value
literalAt env (si, r, c) = case Seq.lookup si (envGrids env) >>= Seq.lookup r >>= Seq.lookup c of
  Nothing -> VBlank
  Just t
    | T.null t -> VBlank
    | Just d <- readNumber t -> VNum d
    | T.toUpper t == "TRUE"  -> VBool True
    | T.toUpper t == "FALSE" -> VBool False
    | otherwise -> VText t

evalExpr :: Env -> Ctx -> Expr -> St -> (Value, St)
evalExpr env ctx expr st0 = case expr of
  ENum d    -> (VNum d, st0)
  EStr s    -> (VText s, st0)
  EBool b   -> (VBool b, st0)
  ELitErr e -> (VErr e, st0)

  ERef sh c r -> case resolveSheet env ctx sh of
    Nothing -> (errRef, st0)
    Just si -> evalCell env ctx (si, r, c) st0

  -- An area used where a single value is wanted is an error; the functions
  -- that take ranges read them through 'valuesOf' instead.
  EArea{} -> (errValue, st0)

  ENeg e -> num1 e negate
  EPercent e -> num1 e (/ 100)

  EBin op a b ->
    let (va, st1) = evalExpr env ctx a st0
        (vb, st2) = evalExpr env ctx b st1
    in (binop op va vb, st2)

  ECall f as -> callFn env ctx (T.toUpper f) as st0
  where
    num1 e f = let (v, st1) = evalExpr env ctx e st0
               in (either id (VNum . f) (asNum v), st1)

resolveSheet :: Env -> Ctx -> Maybe Text -> Maybe Int
resolveSheet _   ctx Nothing   = case ctxHere ctx of Just (si, _, _) -> Just si; Nothing -> Just 0
resolveSheet env _   (Just nm) = M.lookup (T.toLower nm) (envByName env)

binop :: Text -> Value -> Value -> Value
binop op a b = case op of
  "&" -> case (a, b) of
           (VErr _, _) -> a
           (_, VErr _) -> b
           _           -> VText (asText a <> asText b)
  "=" -> cmp (== EQ)
  "<>"-> cmp (/= EQ)
  "<" -> cmp (== LT)
  ">" -> cmp (== GT)
  "<="-> cmp (/= GT)
  ">="-> cmp (/= LT)
  _   -> arith
  where
    arith = case (asNum a, asNum b) of
      (Left e, _) -> e
      (_, Left e) -> e
      (Right x, Right y) -> case op of
        "+" -> VNum (x + y)
        "-" -> VNum (x - y)
        "*" -> VNum (x * y)
        "/" -> if y == 0 then errDiv0 else VNum (x / y)
        "^" -> let r = x ** y in if isNaN r || isInfinite r then errNum else VNum r
        _   -> errValue
    -- Comparison follows Excel's type ordering: numbers sort before text
    -- before booleans, and text compares case-insensitively.
    cmp p = case (a, b) of
      (VErr _, _) -> a
      (_, VErr _) -> b
      _           -> VBool (p (compareValues a b))

compareValues :: Value -> Value -> Ordering
compareValues a b = case (norm a, norm b) of
  (VNum x, VNum y)   -> compare x y
  (VText x, VText y) -> compare (T.toLower x) (T.toLower y)
  (VBool x, VBool y) -> compare x y
  (x, y)             -> compare (rank x) (rank y)
  where
    -- A blank compares as the zero/empty of whatever it is up against.
    norm VBlank = case (a, b) of
      (VBlank, VText _) -> VText T.empty
      (VText _, VBlank) -> VText T.empty
      (VBlank, VBool _) -> VBool False
      (VBool _, VBlank) -> VBool False
      _                 -> VNum 0
    norm v = v
    rank v = case v of VNum _ -> 0 :: Int; VText _ -> 1; VBool _ -> 2; _ -> 3

