  , "MEDIAN", "SUMPRODUCT"
  , "IF", "IFERROR", "IFNA", "AND", "OR", "NOT", "TRUE", "FALSE"
  , "SUMIF", "COUNTIF", "AVERAGEIF"
  , "ABS", "ROUND", "ROUNDUP", "ROUNDDOWN", "INT", "TRUNC", "MOD", "POWER"
  , "SQRT", "SIGN", "EXP", "LN", "LOG10", "PI", "CEILING", "FLOOR"
  , "LEN", "LEFT", "RIGHT", "MID", "UPPER", "LOWER", "TRIM", "CONCATENATE"
