-- | A small spreadsheet formula evaluator, for the cells a workbook does not
-- answer for itself.
--
-- __Read this first: the cached value always wins.__ Excel, LibreOffice and
-- Numbers all write the result of every formula into the file beside it (the
-- @\<v\>@ element), so for a workbook a real spreadsheet program saved,
-- "Cmedit.Xlsx" already shows the right number — computed by the program that
-- owns the format, with full fidelity, including the hundreds of functions
-- this module will never have. Evaluating those cells ourselves could at best
-- reproduce an answer we already have, and at worst quietly contradict it.
--
-- So this module runs on exactly one case: __a formula with no cached value__.
-- That is not a corner case. Workbooks generated by libraries — @openpyxl@,
-- @xlsxwriter@, @pandas.to_excel@ — write the formula and nothing else,
-- because they are not spreadsheet engines either. Before this module those
-- cells showed /blank/, which is the one answer that is certainly wrong. The
-- rule that follows is worth stating plainly: __this never overrides a value
-- the file already gives.__
--
-- __What it does not do.__ No dates or times (@TODAY@ and @NOW@ need a clock,
-- and this module is pure), no number formats (a result is shown the way the
-- file's own cached values are — raw), no array formulas, no defined names, no
-- external workbooks, no volatile or financial functions. A formula this
-- module cannot parse, or that calls a function it does not have, is __left
-- exactly as it was__ — blank — and counted, so the status bar can say how
-- many. Showing nothing is the honest answer to "I do not understand this";
-- showing a number would not be.
--
-- A genuine spreadsheet error is different, and /is/ shown: @#DIV\/0!@ is the
-- answer to @=1\/0@, not a failure to evaluate it.
--
-- Everything here is bounded, since the input is a file we did not write:
-- circular references are detected rather than followed ('maxDepth'), the
-- whole pass has a step budget ('maxSteps'), and the number of formula cells
-- it will attempt is capped ('maxFormulaCells').
--
-- Leaf module: it imports nothing from @Cmedit@, so "Cmedit.Xlsx" and the
-- tests can both use it cycle-free.
module Cmedit.Formula
  ( -- * Values
    Value(..)
  , showNumber
    -- * The formula language
  , Expr(..)
  , parseFormula
  , supportedFunctions
    -- * Evaluating a workbook
  , SheetIn(..)
  , Grid
  , evalWorkbook
  , maxFormulaCells
  , maxSteps
  , maxDepth
  ) where

import Data.Char (isAlpha, isDigit, isSpace, ord, toUpper)
import Data.Foldable (toList)
