-- Evaluate a function's arguments, keeping ranges as ranges (the aggregates
-- need every cell) and everything else as a single value.
data Arg = AVal !Value | ARange ![Value]

callFn :: Env -> Ctx -> Text -> [Expr] -> St -> (Value, St)
callFn env ctx f as st0 = case f of
  -- The short-circuiting ones evaluate their arguments themselves.
  "IF" -> case as of
    (c : t : rest) ->
      let (cv, st1) = evalExpr env ctx c st0
      in case asBool cv of
           Left e      -> (e, st1)
           Right True  -> evalExpr env ctx t st1
           Right False -> case rest of
             (e : _) -> evalExpr env ctx e st1
             []      -> (VBool False, st1)
    _ -> (errValue, st0)
  "IFERROR" -> guardErr (\v -> case v of VErr _ -> True; _ -> False)
  "IFNA"    -> guardErr (== errNA)
  _ -> let (args, st1) = evalArgs env ctx as st0
       in (applyFn f args, st1)
  where
    guardErr isBad = case as of
      [a, b] -> let (v, st1) = evalExpr env ctx a st0
                in if isBad v then evalExpr env ctx b st1 else (v, st1)
      _      -> (errValue, st0)

evalArgs :: Env -> Ctx -> [Expr] -> St -> ([Arg], St)
evalArgs env ctx as st0 = go as st0
  where
    go [] st = ([], st)
    go (e : rest) st =
      let (a, st1) = evalArg env ctx e st
          (bs, st2) = go rest st1
      in (a : bs, st2)

evalArg :: Env -> Ctx -> Expr -> St -> (Arg, St)
evalArg env ctx e st = case e of
  EArea sh c0 r0 c1 r1 -> case resolveSheet env ctx sh of
    Nothing -> (AVal errRef, st)
    Just si ->
      let g  = fromMaybe Seq.empty (Seq.lookup si (envGrids env))
          nr = Seq.length g
          nc = maximum (0 : map Seq.length (toList g))
          rr = [max 0 r0 .. min (nr - 1) (if r1 == maxBound then nr - 1 else r1)]
          cc = [max 0 c0 .. min (nc - 1) (if c1 == maxBound then nc - 1 else c1)]
          step (vs, s) (r, c) = let (v, s') = evalCell env ctx (si, r, c) s in (v : vs, s')
          (vals, st') = foldl' step ([], st) [ (r, c) | r <- rr, c <- cc ]
      in (ARange (reverse vals), st')
  _ -> let (v, st') = evalExpr env ctx e st in (AVal v, st')

-- Every value an argument stands for (a range flattens, a scalar is itself).
argVals :: Arg -> [Value]
argVals (AVal v)   = [v]
argVals (ARange vs) = vs

-- Numbers for an aggregate. Excel's rule: text and blanks inside a *range* are
-- ignored, but a scalar argument is coerced — @SUM(A1:A9)@ skips a stray label,
-- @SUM("3")@ is 3.
aggNums :: [Arg] -> Either Value [Double]
aggNums = foldr step (Right [])
  where
    step a acc = case acc of
      Left e -> Left e
      Right ns -> case a of
        AVal v -> case asNum v of
          Left e  -> Left e
          Right d -> Right (d : ns)
        ARange vs -> case firstErr vs of
          Just e  -> Left e
          Nothing -> Right ([ d | VNum d <- vs ] ++ ns)
    firstErr vs = case [ v | v@(VErr _) <- vs ] of (e : _) -> Just e; [] -> Nothing

applyFn :: Text -> [Arg] -> Value
applyFn f args = case f of
  "SUM"     -> agg sum
  "PRODUCT" -> agg product
  "AVERAGE" -> aggNE (\ns -> sum ns / fromIntegral (length ns))
  "MIN"     -> aggNE minimum
  "MAX"     -> aggNE maximum
  "MEDIAN"  -> aggNE median
  "COUNT"   -> VNum (fromIntegral (length [ () | v <- vals, isNumV v ]))
  "COUNTA"  -> VNum (fromIntegral (length [ () | v <- vals, v /= VBlank ]))
  "COUNTBLANK" -> VNum (fromIntegral (length [ () | v <- vals, v == VBlank ]))
  "SUMPRODUCT" -> case map (mapMaybe numOf . argVals) args of
    (xs : rest) | not (null rest)
      , all ((== length xs) . length) rest ->
          VNum (sum (foldl' (zipWith (*)) xs rest))
    [xs] -> VNum (sum xs)
    _    -> errValue

  "TRUE"  -> VBool True
  "FALSE" -> VBool False
  "AND"   -> logical and
  "OR"    -> logical or
  "NOT"   -> one1 (\v -> either id (VBool . not) (asBool v))

  "SUMIF"     -> condAgg (\ms -> VNum (sum ms))
  "AVERAGEIF" -> condAgg (\ms -> if null ms then errDiv0
                                   else VNum (sum ms / fromIntegral (length ms)))
  "COUNTIF" -> case args of
    [ARange rs, AVal c] -> VNum (fromIntegral (length (filter (matches c) rs)))
    [AVal r, AVal c]    -> VNum (if matches c r then 1 else 0)
    _                   -> errValue

  "ABS"   -> num1 abs
  "INT"   -> num1 (fromIntegral . (floor :: Double -> Integer))
  "TRUNC" -> num1 (fromIntegral . (truncate :: Double -> Integer))
  "SIGN"  -> num1 (\x -> if x > 0 then 1 else if x < 0 then -1 else 0)
  "SQRT"  -> num1' (\x -> if x < 0 then errNum else VNum (sqrt x))
  "EXP"   -> num1 exp
  "LN"    -> num1' (\x -> if x <= 0 then errNum else VNum (log x))
  "LOG10" -> num1' (\x -> if x <= 0 then errNum else VNum (logBase 10 x))
  "PI"    -> VNum pi
  "ROUND"     -> round2 roundTo
  "ROUNDUP"   -> round2 (dirRound (ceilingAway))
  "ROUNDDOWN" -> round2 (dirRound (truncateToward))
  "MOD" -> num2 (\x y -> if y == 0 then errDiv0
                           else VNum (x - y * fromIntegral (floor (x / y) :: Integer)))
  "POWER" -> num2 (\x y -> let r = x ** y in if isNaN r || isInfinite r then errNum else VNum r)
  "CEILING" -> num2 (\x s -> if s == 0 then VNum 0 else VNum (ceilingAway (x / s) * s))
  "FLOOR"   -> num2 (\x s -> if s == 0 then errDiv0 else VNum (truncateToward (x / s) * s))

  "LEN"   -> one1 (VNum . fromIntegral . T.length . asText)
  "UPPER" -> text1 T.toUpper
  "LOWER" -> text1 T.toLower
  "TRIM"  -> text1 (T.unwords . T.words)
  "LEFT"  -> textN (\t n -> T.take n t)
  "RIGHT" -> textN (\t n -> T.takeEnd n t)
  "MID"   -> case scalars of
    [a, b, c] -> withNums [b, c] (\ns -> case ns of
                   [s, n] -> VText (T.take (max 0 (truncate n))
                                     (T.drop (max 0 (truncate s - 1)) (asText a)))
                   _      -> errValue)
    _ -> errValue
  "REPT" -> case scalars of
    [a, b] -> withNums [b] (\ns -> case ns of
                [n] | n < 0 -> errValue
                    -- Bounded: a file can ask for REPT("x", 1e9).
                    | otherwise -> VText (T.replicate (min 32768 (truncate n)) (asText a))
                _ -> errValue)
    _ -> errValue
  "SUBSTITUTE" -> case scalars of
    (a : b : c : _) | not (T.null (asText b)) ->
                        VText (T.replace (asText b) (asText c) (asText a))
                    | otherwise -> VText (asText a)
    _ -> errValue
  "CONCATENATE" -> VText (T.concat (map asText vals))
  "CONCAT"      -> VText (T.concat (map asText vals))
  "TEXTJOIN" -> case args of
    (AVal sep : AVal skipV : rest) ->
      let skip = either (const True) id (asBool skipV)
          parts = concatMap argVals rest
          keep v = not skip || v /= VBlank
      in VText (T.intercalate (asText sep) (map asText (filter keep parts)))
    _ -> errValue

  "ISBLANK"  -> one1 (VBool . (== VBlank))
  "ISNUMBER" -> one1 (VBool . isNumV)
  "ISTEXT"   -> one1 (\v -> VBool (case v of VText _ -> True; _ -> False))
  "ISERROR"  -> one1 (\v -> VBool (case v of VErr _ -> True; _ -> False))
  "N"        -> one1 (\v -> either (const (VNum 0)) VNum (asNum v))

  "VLOOKUP" -> lookupFn False
  "HLOOKUP" -> lookupFn True
  "MATCH" -> case args of
    (AVal needle : ARange hay : rest) ->
      let approx = case rest of
                     (AVal m : _) -> either (const 1) id (fmap truncate (asNum m)) /= (0 :: Int)
                     _            -> True
      in matchIn needle hay approx
    _ -> errValue
  "INDEX" -> case args of
    (ARange rs : rest) -> withNums (concatMap argVals rest) (\ns ->
      let i = case ns of (n : _) -> truncate n - 1; _ -> 0
      in if i >= 0 && i < length rs then rs !! i else errRef)
    _ -> errValue

  _ -> errName
  where
    vals    = concatMap argVals args
    scalars = [ v | AVal v <- args ] ++ [ v | ARange (v : _) <- args ]

    isNumV v = case v of VNum _ -> True; _ -> False
    numOf v  = case v of VNum d -> Just d; _ -> Nothing

    agg g   = either id (VNum . g) (aggNums args)
    aggNE g = case aggNums args of
      Left e   -> e
      Right [] -> if f == "AVERAGE" then errDiv0 else VNum 0
      Right ns -> VNum (g ns)
    median ns = let s = sortBy compare ns; n = length s
                in if even n then (s !! (n `div` 2 - 1) + s !! (n `div` 2)) / 2
                             else s !! (n `div` 2)

    logical g = case mapM asBool [ v | v <- vals, v /= VBlank ] of
      Left e   -> e
      Right [] -> errValue
      Right bs -> VBool (g bs)

    one1 g = case scalars of (v : _) -> g v; _ -> errValue
    text1 g = one1 (VText . g . asText)
    textN g = case scalars of
      [a]    -> VText (g (asText a) 1)
      [a, b] -> withNums [b] (\ns -> case ns of
                  (n : _) -> VText (g (asText a) (max 0 (truncate n)))
                  _       -> errValue)
      _ -> errValue
    num1 g  = one1 (\v -> either id (VNum . g) (asNum v))
    num1' g = one1 (\v -> either id g (asNum v))
    num2 g = case scalars of
      (a : b : _) -> case (asNum a, asNum b) of
        (Left e, _) -> e
        (_, Left e) -> e
        (Right x, Right y) -> g x y
      _ -> errValue
    round2 g = case scalars of
      [a]         -> withNums [a] (\ns -> case ns of (x : _) -> VNum (g x 0); _ -> errValue)
      (a : b : _) -> case (asNum a, asNum b) of
        (Left e, _) -> e
        (_, Left e) -> e
        (Right x, Right d) -> VNum (g x (truncate d))
      _ -> errValue

    withNums vs g = case mapM asNum vs of
      Left e   -> e
      Right ns -> g ns

    -- SUMIF/AVERAGEIF: (range, criterion, [sum range]).
    condAgg g = case args of
      [ARange rs, AVal c]            -> g [ d | VNum d <- rs, matches c (VNum d) ]
      [ARange rs, AVal c, ARange ss] ->
        g [ d | (r, VNum d) <- zip rs ss, matches c r ]
      _ -> errValue

    lookupFn horizontal = case args of
      (AVal needle : ARange hay : rest) ->
        let idx = case rest of
                    (a : _) -> either (const 0) truncate (asNum (headOf a))
                    _       -> 0
            headOf a = case argVals a of (v : _) -> v; [] -> VBlank
            approx = case drop 1 rest of
                       (a : _) -> either (const True) id (asBool (headOf a))
                       _       -> True
        in vlookupIn needle hay idx approx horizontal
      _ -> errValue

    -- A range arrives flattened row-major, so a lookup has to know the shape.
    -- It does not, so this supports the overwhelmingly common shape: the key
    -- in the first column (or row) and the answer a fixed offset along. Any
    -- other shape yields #N/A rather than a plausible wrong row.
    vlookupIn needle hay idx _approx horizontal
      | idx < 1 || null hay = errValue
      | otherwise =
          let w = if horizontal then length hay else idx
              rowsOf = chunk (max 1 w) hay
              keyOf r = case r of (v : _) -> v; [] -> VBlank
          in case [ r | r <- rowsOf, compareValues (keyOf r) needle == EQ ] of
               (r : _) | idx <= length r -> r !! (idx - 1)
               _ -> errNA

    matchIn needle hay approx =
      case [ i | (i, v) <- zip [1 :: Int ..] hay, compareValues v needle == EQ ] of
        (i : _) -> VNum (fromIntegral i)
        [] | approx ->
               case [ i | (i, v) <- zip [1 :: Int ..] hay, compareValues v needle /= GT ] of
                 [] -> errNA
                 is -> VNum (fromIntegral (last is))
           | otherwise -> errNA

chunk :: Int -> [a] -> [[a]]
chunk n xs | n <= 0 = [xs]
           | otherwise = go xs
  where go [] = []
        go ys = let (a, b) = splitAt n ys in a : go b

-- Excel rounds half away from zero, unlike Haskell's banker's rounding.
roundTo :: Double -> Int -> Double
roundTo x d = let p = 10 ** fromIntegral d
              in ceilingAway' (x * p) / p
  where ceilingAway' v = fromIntegral (truncate (v + (if v < 0 then -0.5 else 0.5)) :: Integer)

dirRound :: (Double -> Double) -> Double -> Int -> Double
dirRound g x d = let p = 10 ** fromIntegral d in g (x * p) / p

ceilingAway :: Double -> Double
ceilingAway v = fromIntegral (if v < 0 then floor v else ceiling v :: Integer)

truncateToward :: Double -> Double
truncateToward v = fromIntegral (truncate v :: Integer)

-- | Does a value satisfy a SUMIF\/COUNTIF criterion? The criterion is either a
-- value to equal, or text starting with a comparison operator (@\"\>5\"@), or
-- text with @*@ and @?@ wildcards.
matches :: Value -> Value -> Bool
matches crit v = case crit of
  VText t
    | Just (op, rest) <- splitOp t ->
        let rhs = maybe (VText rest) VNum (readNumber rest)
            o = compareValues v rhs
        in case op of
             "=" -> o == EQ
             "<>"-> o /= EQ
             ">" -> o == GT
             "<" -> o == LT
             ">="-> o /= LT
             _   -> o /= GT
    | T.any (`elem` ("*?" :: String)) t -> wildcard (T.toLower t) (T.toLower (asText v))
  _ -> compareValues v crit == EQ
  where
    splitOp t = case [ o | o <- [">=", "<=", "<>", ">", "<", "="], o `T.isPrefixOf` t ] of
      (o : _) -> Just (o, T.strip (T.drop (T.length o) t))
      []      -> Nothing

-- Memo-free glob: the patterns are user criteria a handful of characters long,
-- and the subject is one cell.
wildcard :: Text -> Text -> Bool
wildcard pat s = go (T.unpack pat) (T.unpack s)
  where
    go [] []             = True
    go ('*' : ps) xs     = go ps xs || (not (null xs) && go ('*' : ps) (drop 1 xs))
    go ('?' : ps) (_ : xs) = go ps xs
    go (p : ps) (x : xs) = p == x && go ps xs
    go _ _               = False
