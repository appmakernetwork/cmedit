-- The set is chosen by what actually appears in generated workbooks: the
-- aggregates, the conditional, the rounding family, the text handling and one
-- lookup. Each is small; what keeps them honest is that anything /not/ here
-- makes the whole formula unsupported up front ('parseFormula'), so a cell is
-- never half-computed.

-- | Every function name this module implements.
supportedFunctions :: [Text]
